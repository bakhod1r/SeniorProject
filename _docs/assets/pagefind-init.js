/* ================================================================
   Pagefind UI integration

   Replaces MkDocs Material's built-in Lunr-based search (which built
   a 124 MB client-side index that crashed browsers on this site's
   ~1,300 pages) with Pagefind — a WASM search engine that ships a
   chunked index and only fetches the segments needed for the current
   query (~50 KB upfront, ~10 MB peak RAM vs Material's 500 MB-1.5 GB).

   The Pagefind UI assets live in /pagefind/, generated by
   `npx pagefind --site _site` AFTER `mkdocs build`. We load them
   lazily on first open so the homepage doesn't pay for them.

   Triggers: Cmd/Ctrl+K, the `/` key (when not typing), and the
   floating search button injected bottom-right.
   ================================================================ */
(function () {
  const PAGEFIND_BASE = "/pagefind/";
  let uiReady = null;
  let dialog = null;
  let pagefindUI = null;

  function loadPagefindUI() {
    if (uiReady) return uiReady;
    uiReady = new Promise((resolve, reject) => {
      const css = document.createElement("link");
      css.rel = "stylesheet";
      css.href = PAGEFIND_BASE + "pagefind-ui.css";
      document.head.appendChild(css);

      const js = document.createElement("script");
      js.src = PAGEFIND_BASE + "pagefind-ui.js";
      js.onload = () => {
        if (typeof PagefindUI === "undefined") {
          reject(new Error("PagefindUI global missing after script load"));
          return;
        }
        resolve(window.PagefindUI);
      };
      js.onerror = () => reject(new Error("failed to load pagefind-ui.js — did `pagefind --site _site` run after build?"));
      document.head.appendChild(js);
    });
    return uiReady;
  }

  function buildDialog() {
    if (dialog) return dialog;
    dialog = document.createElement("dialog");
    dialog.className = "sp-pagefind-dialog";
    dialog.innerHTML =
      '<div class="sp-pagefind-dialog__inner">' +
        '<button type="button" class="sp-pagefind-dialog__close" aria-label="Close search">&times;</button>' +
        '<div id="sp-pagefind-mount"></div>' +
      '</div>';
    document.body.appendChild(dialog);

    dialog.querySelector(".sp-pagefind-dialog__close").addEventListener("click", () => closeDialog());
    dialog.addEventListener("click", (e) => {
      if (e.target === dialog) closeDialog();
    });
    dialog.addEventListener("close", () => {
      document.documentElement.classList.remove("sp-pagefind-open");
    });
    return dialog;
  }

  function showLoadError(d, err) {
    const mount = d.querySelector("#sp-pagefind-mount");
    if (!mount) return;
    mount.innerHTML =
      '<div class="sp-pagefind-error">' +
        '<p><strong>Search unavailable.</strong></p>' +
        '<p>The Pagefind index was not found at <code>/pagefind/</code>. ' +
        'If you are running <code>mkdocs serve</code> locally, search only works after a full build:</p>' +
        '<pre><code>./scripts/build.sh &amp;&amp; python -m http.server -d _site 8000</code></pre>' +
      '</div>';
    console.warn("[sp] pagefind UI load failed:", err);
  }

  function openDialog() {
    const d = buildDialog();
    if (!d.open) d.showModal();
    document.documentElement.classList.add("sp-pagefind-open");

    loadPagefindUI()
      .then((UI) => {
        if (!pagefindUI) {
          pagefindUI = new UI({
            element: "#sp-pagefind-mount",
            bundlePath: PAGEFIND_BASE,
            showImages: false,
            showSubResults: true,
            resetStyles: false,
            autofocus: true,
            excerptLength: 25,
          });
        }
        setTimeout(() => {
          const input = d.querySelector(".pagefind-ui__search-input");
          if (input) input.focus();
        }, 50);
      })
      .catch((err) => showLoadError(d, err));
  }

  function closeDialog() {
    if (dialog && dialog.open) dialog.close();
  }

  function injectButton() {
    if (document.querySelector(".sp-pagefind-trigger")) return;
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "sp-pagefind-trigger";
    btn.setAttribute("aria-label", "Search (Cmd+K)");
    btn.innerHTML =
      '<span class="sp-pagefind-trigger__icon" aria-hidden="true">$</span>' +
      '<span class="sp-pagefind-trigger__label">search</span>' +
      '<kbd class="sp-pagefind-trigger__kbd">⌘K</kbd>';
    btn.addEventListener("click", openDialog);
    document.body.appendChild(btn);
  }

  function isTypingTarget(el) {
    if (!el) return false;
    const tag = el.tagName;
    return tag === "INPUT" || tag === "TEXTAREA" || tag === "SELECT" || el.isContentEditable;
  }

  function bindShortcuts() {
    document.addEventListener("keydown", (e) => {
      const isOpen = dialog && dialog.open;
      // Cmd/Ctrl + K — toggle from anywhere
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === "k") {
        e.preventDefault();
        isOpen ? closeDialog() : openDialog();
        return;
      }
      // `/` — open, but only if user isn't typing in a field
      if (e.key === "/" && !isOpen && !isTypingTarget(e.target)) {
        e.preventDefault();
        openDialog();
        return;
      }
      // Esc — handled natively by <dialog>
    });
  }

  function init() {
    injectButton();
  }

  // Bind shortcuts once at script load (global, not per-page).
  bindShortcuts();

  // Re-inject button on Material instant nav.
  if (typeof document$ !== "undefined" && document$.subscribe) {
    document$.subscribe(init);
  } else if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
